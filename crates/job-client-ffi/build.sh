#!/usr/bin/env bash
# Build the job client's kernel as WASM and inline it into the TypeScript SDK.
#
#   crates/job-client-ffi/build.sh           rebuild when the sources changed, write the artifacts
#   crates/job-client-ffi/build.sh --check   rebuild always; fail if the committed artifacts differ
#
# Writes sdk/ts/sandbox/src/kernel/wasm.ts (the module as base64, inlined: no fetch and no file at
# runtime) and kernel.src.sha256 beside it: the hash of the sources it was built from. The TS test
# `kernel-pin.test.ts` fails when a source changed and this did not run; CI's `--check` fails when the
# committed bytes are not what the sources build to.
set -euo pipefail
here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
root=$(cd "$here/../.." && pwd)
out=$root/sdk/ts/sandbox/src/kernel
mkdir -p "$out"
check=0
[[ ${1:-} == --check ]] && check=1

# The sources the module is built from: this crate and the kernel, by content (the paths are not hashed).
# The compiler is part of the bytes: it is pinned in `toolchain` (an exact release) and hashed with the sources,
# so a rustc bump is a visible change here and never a surprise red in CI.
toolchain=$(tr -d '[:space:]' <"$here/toolchain")
export RUSTUP_TOOLCHAIN=$toolchain
src_hash=$(cd "$root/crates" && cat job-client-ffi/toolchain job-client-ffi/Cargo.toml job-client/Cargo.toml $(LC_ALL=C ls job-client-ffi/src/*.rs job-client/src/*.rs) | sha256sum | cut -d' ' -f1)
if [[ $check == 0 && -f $out/wasm.ts && "$(cat "$out/kernel.src.sha256" 2>/dev/null)" == "$src_hash" ]]; then exit 0; fi

target=${CARGO_TARGET_DIR:-$HOME/.cache/job-client-ffi-target}
export CARGO_TARGET_DIR=$target
# Size, and the same bytes from any checkout: the profile is set here, not in the workspace's, and the
# paths the compiler would embed are remapped.
export CARGO_PROFILE_RELEASE_OPT_LEVEL=s CARGO_PROFILE_RELEASE_LTO=true CARGO_PROFILE_RELEASE_PANIC=abort
export CARGO_PROFILE_RELEASE_CODEGEN_UNITS=1 CARGO_PROFILE_RELEASE_STRIP=true CARGO_PROFILE_RELEASE_OVERFLOW_CHECKS=true
export RUSTFLAGS="--remap-path-prefix=$root=/src --remap-path-prefix=${CARGO_HOME:-$HOME/.cargo}=/cargo --remap-path-prefix=${RUSTUP_HOME:-$HOME/.rustup}=/rustup"
# The shared compile cache (mbx) must not serve this build: the bytes are a pinned artifact, and a cache hit
# built under other flags gave different bytes than a clean checkout does.
export MBX_OFF=1
slot=${BUILD_SLOT:-$HOME/.cache/tmp/build-slot.sh}
[[ -x $slot ]] || slot=
(cd "$root" && $slot cargo build --release --locked --lib --target wasm32-unknown-unknown -p beyond-job-client-ffi)
wasm=$target/wasm32-unknown-unknown/release/job_client_ffi.wasm

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
{
  echo "// Generated by crates/job-client-ffi/build.sh from kernel.src.sha256's sources. Do not edit."
  echo "/** The job client's kernel, WASM, base64. */"
  echo "export const KERNEL_WASM_BASE64 ="
  echo "  \"$(base64 -w0 "$wasm")\";"
} >"$tmp"

if [[ $check == 1 ]]; then
  cmp -s "$tmp" "$out/wasm.ts" || { echo "kernel/wasm.ts is not what the sources build to: run crates/job-client-ffi/build.sh" >&2; exit 1; }
  [[ "$(cat "$out/kernel.src.sha256")" == "$src_hash" ]] || { echo "kernel.src.sha256 is stale: run crates/job-client-ffi/build.sh" >&2; exit 1; }
  exit 0
fi
cp "$tmp" "$out/wasm.ts"
echo "$src_hash" >"$out/kernel.src.sha256"
echo "wasm $(stat -c %s "$wasm") bytes"
