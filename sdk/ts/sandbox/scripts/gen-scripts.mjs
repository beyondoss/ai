// Regenerates src/scripts.ts, the shell scripts every helper sends byte for byte.
//
//   node scripts/gen-scripts.mjs [repo-root]
//
// Sources, both in this repository:
//   - sdk/conformance/FILES-OVER-EXEC.md, appendix "The scripts" (A to F): the file helpers.
//   - the baseline jobs of the exec protocol: JOB_SCRIPT and the supervisor
//     (crates/agent/src/exec_endpoint/jobs.rs, with the v1.4 shell kernel from
//     crates/exec-notify/src/lib.rs spliced in at `#@kernel`, as the Rust client does).
// The scripts are constants, never edited by hand: __tests__/scripts.test.ts fails when
// scripts.ts and the spec disagree.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(process.argv[2] ?? join(here, "../../../.."));
const read = (p) => readFileSync(join(root, p), "utf8");

const md = read("sdk/conformance/FILES-OVER-EXEC.md");
const appendix = md.slice(md.indexOf("## 7. Appendix: the scripts"));
function mdScript(letter) {
  const re = new RegExp(
    `### ${letter}\\. [^\\n]*\\n\\n\`\`\`sh\\n([\\s\\S]*?)\\n\`\`\``,
  );
  const m = appendix.match(re);
  if (!m) throw new Error(`script ${letter} not found in the spec`);
  return m[1];
}

function rustRaw(src, name, kind) {
  const re = new RegExp(`${kind} ${name}[^=]*=\\s*r#"([\\s\\S]*?)"#;`);
  const m = src.match(re);
  if (!m) throw new Error(`${name} not found`);
  return m[1];
}

const jobs = read("crates/agent/src/exec_endpoint/jobs.rs");
const notify = read("crates/exec-notify/src/lib.rs");
const kernel = rustRaw(notify, "SH", "pub const");
const supervisorTemplate = rustRaw(jobs, "SUPERVISOR_TEMPLATE", "const");
const out = {
  STAT_SCRIPT: mdScript("A"),
  READ_SCRIPT: mdScript("B"),
  WRITE_STDIN_SCRIPT: mdScript("C"),
  WRITE_CHUNK_SCRIPT: mdScript("D"),
  REMOVE_TEMP_SCRIPT: mdScript("E"),
  GIT_SCRIPT: mdScript("F"),
  JOB_SCRIPT: rustRaw(jobs, "JOB_SCRIPT", "pub const"),
  SUPERVISOR: supervisorTemplate.replace("#@kernel\n", () => kernel),
};
let ts =
  "// @generated by scripts/gen-scripts.mjs from FILES-OVER-EXEC.md (appendix) and the baseline jobs\n"
  + "// of the exec protocol. Do not edit: the scripts are sent byte for byte.\n\n";
for (const [k, v] of Object.entries(out)) {
  ts += `export const ${k} = ${JSON.stringify(v)};\n\n`;
}
const target = join(here, "../src/scripts.ts");
writeFileSync(target, ts.trimEnd() + "\n");

console.log("wrote src/scripts.ts", Object.keys(out).join(" "));
