// Regenerates src/scripts.ts, the shell scripts every helper sends byte for byte.
//
//   node scripts/gen-scripts.mjs [repo-root]
//
// Source: sdk/conformance/FILES-OVER-EXEC.md, appendix "The scripts", looked up by script name (the
// appendix letters may change). The scripts are constants, never edited by hand:
// __tests__/scripts.test.ts fails when scripts.ts and the spec disagree.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(process.argv[2] ?? join(here, "../../../.."));
const read = (p) => readFileSync(join(root, p), "utf8");

const md = read("sdk/conformance/FILES-OVER-EXEC.md");
const appendix = md.slice(md.indexOf("## 7. Appendix: the scripts"));
function mdScript(name) {
  const re = new RegExp(
    `### [A-Z]\\. ${name}[^\\n]*\\n\\n\`\`\`sh\\n([\\s\\S]*?)\\n\`\`\``,
  );
  const m = appendix.match(re);
  if (!m) throw new Error(`script ${name} not found in the spec`);
  return m[1];
}

const out = {};
for (
  const name of [
    "STAT_SCRIPT",
    "READ_SCRIPT",
    "WRITE_STDIN_SCRIPT",
    "REMOVE_TEMP_SCRIPT",
    "GIT_SCRIPT",
  ]
) out[name] = mdScript(name);
let ts =
  "// @generated by scripts/gen-scripts.mjs from FILES-OVER-EXEC.md (appendix). Do not edit: the\n"
  + "// scripts are sent byte for byte.\n\n";
for (const [k, v] of Object.entries(out)) {
  ts += `export const ${k} = ${JSON.stringify(v)};\n\n`;
}
const target = join(here, "../src/scripts.ts");
writeFileSync(target, ts.trimEnd() + "\n");

console.log("wrote src/scripts.ts", Object.keys(out).join(" "));
