"""Regenerate src/beyond_sandbox/_scripts.py from the Rust reference.

The shell scripts are constants that every client must send byte for byte, so they are
extracted from the reference sources instead of being retyped. Run from anywhere:

    python scripts/gen_scripts.py            # rewrite _scripts.py
    python scripts/gen_scripts.py --check    # exit 1 if _scripts.py is out of date
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
OUT = Path(__file__).resolve().parents[1] / "src" / "beyond_sandbox" / "_scripts.py"

SHELL = ROOT / "crates/sandbox/src/fs/shell.rs"
JOBS = ROOT / "crates/sandbox/src/exec_endpoint/jobs.rs"
NOTIFY = ROOT / "crates/exec-notify/src/lib.rs"

RAW = r'r#"(.*?)"#'


def raw_const(src: str, name: str) -> str:
    m = re.search(rf"const {name}: [^=]+= {RAW};", src, re.S)
    if not m:
        raise SystemExit(f"constant {name} not found")
    return m.group(1)


def macro(src: str, name: str) -> str:
    m = re.search(rf"macro_rules! {name} \{{\s*\(\) => \{{(.*?)\n    \}};\n\}}", src, re.S)
    if not m:
        raise SystemExit(f"macro {name} not found")
    return "".join(re.findall(RAW, m.group(1), re.S)) if "concat!" not in m.group(1) else m.group(1)


def concat_const(src: str, name: str, macros: dict[str, str]) -> str:
    m = re.search(rf"const {name}: &str = concat!\((.*?)\);\n", src, re.S)
    if not m:
        raise SystemExit(f"concat constant {name} not found")
    out = []
    for tok in re.finditer(rf"{RAW}|(\w+)!\(\)", m.group(1), re.S):
        out.append(tok.group(1) if tok.group(1) is not None else macros[tok.group(2)])
    return "".join(out)


def build() -> dict[str, str]:
    sh = SHELL.read_text()
    resolve = macro(sh, "resolve_target")
    not_dir = macro(sh, "not_a_directory")
    new_temp = not_dir + re.findall(RAW, macro_body(sh, "new_temp"), re.S)[0]
    macros = {
        "resolve_target": resolve,
        "not_a_directory": not_dir,
        "new_temp": new_temp,
        "copy_mode": macro(sh, "copy_mode"),
    }
    jobs = JOBS.read_text()
    return {
        "STAT": raw_const(sh, "STAT_SCRIPT"),
        "GIT_REPO": raw_const(sh, "GIT_REPO_SCRIPT"),
        "READ_WINDOW": raw_const(sh, "READ_WINDOW_SCRIPT"),
        "WRITE_STDIN": concat_const(sh, "WRITE_STDIN_SCRIPT", macros),
        "WRITE_CHUNK": concat_const(sh, "WRITE_CHUNK_SCRIPT", macros),
        "REMOVE_TEMP": concat_const(sh, "REMOVE_TEMP_SCRIPT", macros),
        "JOB": raw_const(jobs, "JOB_SCRIPT"),
        "SUPERVISOR": raw_const(jobs, "SUPERVISOR_TEMPLATE").replace(
            "#@kernel\n", raw_const(NOTIFY.read_text(), "SH"), 1
        ),
    }


def macro_body(src: str, name: str) -> str:
    m = re.search(rf"macro_rules! {name} \{{\s*\(\) => \{{(.*?)\n    \}};\n\}}", src, re.S)
    if not m:
        raise SystemExit(f"macro {name} not found")
    return m.group(1)


def render(scripts: dict[str, str]) -> str:
    parts = [
        '"""The shell scripts of FILES-OVER-EXEC.md section 7 and the jobs baseline.\n\n'
        "Generated by scripts/gen_scripts.py from the Rust reference; do not edit.\n"
        '"""\n\nfrom __future__ import annotations\n'
    ]
    for name, text in scripts.items():
        parts.append(f"\n{name} = {text!r}\n")
    return "".join(parts)


def main() -> int:
    text = render(build())
    if "--check" in sys.argv:
        return 0 if OUT.exists() and OUT.read_text() == text else 1
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
